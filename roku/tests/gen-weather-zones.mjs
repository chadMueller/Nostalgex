#!/usr/bin/env node
// Writes source/weather/WeatherZones.brs: every IANA time zone's UTC offset and its changes (daylight
// saving and the rest) from 2024 to 2035, read from this machine's Intl. The weather channel needs a
// place's local date and hour from MET's UTC timestamps, and a Roku has no time zone database for
// anywhere but the TV's own. Run it again (node tests/gen-weather-zones.mjs) when the span runs short;
// WeatherTests.brs fails when the table ends within a year of the clock.
//
// A zone's entry is "<offset minutes before the first change>;<utc seconds>:<offset minutes>,...".
import { writeFileSync, readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const out = fileURLToPath(new URL("../source/weather/WeatherZones.brs", import.meta.url));
const FROM = Date.UTC(2024, 0, 1) / 1000;
const TO = Date.UTC(2036, 0, 1) / 1000;

const fmts = new Map();
function offsetMin(zone, sec) {
  let f = fmts.get(zone);
  if (!f) {
    f = new Intl.DateTimeFormat("en-US", { timeZone: zone, hourCycle: "h23", year: "numeric", month: "numeric", day: "numeric", hour: "numeric", minute: "numeric", second: "numeric" });
    fmts.set(zone, f);
  }
  const p = {};
  for (const part of f.formatToParts(new Date(sec * 1000))) p[part.type] = Number(part.value);
  const asUtc = Date.UTC(p.year, p.month - 1, p.day, p.hour % 24, p.minute, p.second) / 1000;
  return Math.round((asUtc - sec) / 60);
}

const zones = new Set(Intl.supportedValuesOf("timeZone"));
try {
  // The place files' own zones, in case this Node's list lacks one.
  // node tests/gen-weather-zones.mjs [path to public/weather/places/meta.json]
  const metaPath = process.argv[2] || fileURLToPath(new URL("../../public/weather/places/meta.json", import.meta.url));
  const meta = JSON.parse(readFileSync(metaPath, "utf8"));
  for (const z of meta.tz) zones.add(z);
} catch (e) { /* the place files are on the web branch */ }
zones.add("UTC");

const lines = [];
for (const zone of [...zones].sort()) {
  let first;
  try { first = offsetMin(zone, FROM); } catch (e) { continue; }
  const changes = [];
  let prev = first;
  for (let d = FROM; d < TO; d += 86400) {
    const next = offsetMin(zone, d + 86400);
    if (next !== prev) {
      // The change is inside this day: find the second.
      let lo = d, hi = d + 86400;
      while (hi - lo > 1) {
        const mid = Math.floor((lo + hi) / 2);
        if (offsetMin(zone, mid) === prev) lo = mid; else hi = mid;
      }
      changes.push(`${hi}:${next}`);
      prev = next;
    }
  }
  lines.push(`    z["${zone}"] = "${first};${changes.join(",")}"`);
}

const body = `' Generated by tests/gen-weather-zones.mjs from Intl: do not edit by hand.
'
' Every IANA zone's UTC offset in minutes, and its changes from ${new Date(FROM * 1000).getUTCFullYear()} to ${new Date(TO * 1000).getUTCFullYear() - 1}, for the weather
' channel (a Roku knows no zone but the TV's own). Format per zone:
' "<offset before the first change>;<utc second>:<offset>,...".
'
' Copyright (c) 2026 nostalgex-roku contributors, MIT License.

function NxWxZoneTable() as Object
    z = {}
${lines.join("\n")}
    return { zones: z, fromSec: ${FROM}, toSec: ${TO} }
end function
`;
writeFileSync(out, body);
console.log(`wrote ${out}: ${lines.length} zones, ${(body.length / 1024).toFixed(0)} KB`);
