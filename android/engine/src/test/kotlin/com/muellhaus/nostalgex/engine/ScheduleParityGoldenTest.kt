package com.muellhaus.nostalgex.engine

import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonArray
import kotlinx.serialization.json.JsonElement
import kotlinx.serialization.json.JsonNull
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.JsonPrimitive
import kotlinx.serialization.json.boolean
import kotlinx.serialization.json.int
import kotlinx.serialization.json.jsonArray
import kotlinx.serialization.json.jsonObject
import kotlinx.serialization.json.jsonPrimitive
import kotlinx.serialization.json.long
import kotlinx.serialization.json.longOrNull
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test
import java.io.File
import java.time.ZoneId

/**
 * The Android TV airs what the Apple TV airs, minute for minute.
 *
 * scripts/schedule-parity-golden.json is generated by NostalgexTests/ScheduleParityTests.swift
 * from the Apple TV's own code. This runs the same walk as scripts/schedule-parity-dump.mjs,
 * field for field, and compares every case with the Apple TV's answers.
 */
class ScheduleParityGoldenTest {
    private val repoRoot = File(System.getProperty("nostalgex.repoRoot") ?: "..")
    private val golden = Json.parseToJsonElement(repoRoot.resolve("scripts/schedule-parity-golden.json").readText()).jsonObject
    private val cases = golden["cases"]!!.jsonArray.map { it.jsonObject }

    /** Items as the loaders build them, through the engine's conversions. Null where a loader drops it. */
    private fun makeItem(spec: JsonObject): Pair<String, MediaItem?> {
        spec["compact"]?.let { c ->
            val a = c.jsonArray
            val key = a[0].jsonPrimitive.content
            return key to MediaItem(key, a[1].jsonPrimitive.content, a[2].jsonPrimitive.content, a[3].jsonPrimitive.int, a[4].jsonPrimitive.long)
        }
        val backend = spec["backend"]!!.jsonPrimitive.content
        val kind = spec["kind"]!!.jsonPrimitive.content
        val raw = spec["raw"]!!.jsonObject
        val show = spec["show"]?.jsonObject ?: JsonObject(emptyMap())
        fun str(o: JsonObject, k: String) = (o[k] as? JsonPrimitive)?.takeIf { it !is JsonNull }?.content
        return when (backend) {
            "plex" -> {
                val key = raw["ratingKey"]!!.jsonPrimitive.content
                val minutes = DailyManifest.minutesFromPlexMs((raw["duration"] as? JsonPrimitive)?.longOrNull)
                if (minutes <= 0) return key to null
                val title = if (kind == "episode") str(show, "title") ?: "" else str(raw, "title") ?: ""
                key to MediaItem(key, title, kind, minutes, (raw["addedAt"] as? JsonPrimitive)?.longOrNull ?: 0)
            }
            "jellyfin", "emby" -> {
                val key = raw["Id"]!!.jsonPrimitive.content
                val minutes = DailyManifest.minutesFromTicks((raw["RunTimeTicks"] as? JsonPrimitive)?.longOrNull)
                if (minutes <= 0) return key to null
                val title = if (kind == "episode") str(show, "Name") ?: str(raw, "SeriesName") ?: "" else str(raw, "Name") ?: ""
                key to MediaItem(key, title, kind, minutes, DailyManifest.unixSecondsFromISO(str(raw, "DateCreated")))
            }
            else -> error("unknown item $backend $kind")
        }
    }

    private fun arr(vararg v: Any?): JsonArray = JsonArray(v.map {
        when (it) {
            null -> JsonNull
            is String -> JsonPrimitive(it)
            is Number -> JsonPrimitive(it)
            else -> error("$it")
        }
    })

    private fun dump(fx: JsonObject): JsonObject {
        val zone = ZoneId.of(fx["zone"]!!.jsonPrimitive.content)
        val m = DailyManifest(zone, InMemoryManifestStore())
        val sk = fx["fingerprint"]!!.jsonPrimitive.content

        val byKey = HashMap<String, MediaItem>()
        val items = LinkedHashMap<String, JsonElement>()
        for (spec in fx["items"]!!.jsonArray.map { it.jsonObject }) {
            val (key, item) = makeItem(spec)
            if (item != null) byKey[item.ratingKey] = item
            if (spec["compact"] == null) {
                items[key] = if (item == null) JsonNull else arr(item.duration, maxOf(0L, item.addedAt), item.title, item.type)
            }
        }
        val lineup = fx["channels"]!!.jsonArray.map { it.jsonObject }.map { row ->
            ScheduleChannel(row["id"]!!.jsonPrimitive.int, (row["premiere"] as? JsonPrimitive)?.boolean == true) to
                (row["pool"]?.jsonArray ?: JsonArray(emptyList())).mapNotNull { byKey[it.jsonPrimitive.content] }
        }

        for (t in fx["prime"]?.jsonArray ?: JsonArray(emptyList())) {
            for ((channel, pool) in lineup) m.getManifestBlocks(channel, pool, t.jsonPrimitive.long * 1000, sk)
        }

        val days = LinkedHashMap<String, JsonElement>()
        for (t in fx["days"]?.jsonArray ?: JsonArray(emptyList())) {
            val byChannel = LinkedHashMap<String, JsonElement>()
            for ((channel, pool) in lineup) {
                byChannel[channel.id.toString()] = JsonArray(
                    m.getManifestBlocks(channel, pool, t.jsonPrimitive.long * 1000, sk).map { arr(it.item.ratingKey, it.startSec, it.endSec) },
                )
            }
            days[t.jsonPrimitive.content] = JsonObject(byChannel)
        }

        val at = ArrayList<JsonElement>()
        for (tEl in fx["at"]?.jsonArray ?: JsonArray(emptyList())) {
            val t = tEl.jsonPrimitive.long.toDouble()
            val raw = LinkedHashMap<Int, Schedule>()
            for ((channel, pool) in lineup) m.buildSchedule(channel, pool, t, sk)?.let { raw[channel.id] = it }
            val shown = m.resolveConflicts(LinkedHashMap(raw))
            val byChannel = LinkedHashMap<String, JsonElement>()
            for ((channel, pool) in lineup) {
                val u = raw[channel.id]
                val r = shown[channel.id]
                if (u == null || r == null) {
                    byChannel[channel.id.toString()] = JsonNull
                    continue
                }
                val tune = m.tuneIn(channel, pool, r, t, sk)
                val prev = tune?.item?.ratingKey
                val endOfNow = u.nowPlaying?.endSec?.toDouble() ?: t
                fun adv(now: Double, natural: Boolean): JsonElement =
                    m.advancePick(channel, pool, prev, now, lineup, sk, natural)?.let { arr(it.item.ratingKey, it.seekSeconds) } ?: JsonNull
                val gaveWay = r.entries.firstOrNull { it.isConflict }
                byChannel[channel.id.toString()] = JsonObject(
                    mapOf(
                        "now" to (u.nowPlaying?.let { arr(it.item.ratingKey, it.startSec, it.endSec) } ?: JsonNull),
                        "elapsed" to JsonPrimitive(u.elapsedSeconds),
                        "next" to (u.upNext?.let { JsonPrimitive(it.item.ratingKey) } ?: JsonNull),
                        "span" to arr(
                            u.entries.size,
                            u.entries.firstOrNull()?.startSec ?: 0L,
                            u.entries.lastOrNull()?.endSec ?: 0L,
                        ),
                        "shown" to (r.nowPlaying?.let { arr(it.item.ratingKey, it.startSec) } ?: JsonNull),
                        "shownNext" to (r.upNext?.let { JsonPrimitive(it.item.ratingKey) } ?: JsonNull),
                        "gaveWay" to (gaveWay?.let { JsonPrimitive(it.item.ratingKey) } ?: JsonNull),
                        "tune" to (tune?.let { arr(it.item.ratingKey, it.seekSeconds) } ?: JsonNull),
                        "early" to adv(t, true),
                        "end" to adv(endOfNow, true),
                        "resync" to adv(endOfNow + 600, false),
                    ),
                )
            }
            at.add(JsonObject(mapOf("t" to tEl, "ch" to JsonObject(byChannel))))
        }
        return JsonObject(mapOf("items" to JsonObject(items), "days" to JsonObject(days), "at" to JsonArray(at)))
    }

    /** The first place two JSON values differ, as a path, or null when they are equal. */
    private fun firstDifference(got: JsonElement, want: JsonElement, path: String = "$"): String? {
        if (got is JsonObject && want is JsonObject) {
            for (k in (want.keys + got.keys).sorted()) {
                val g = got[k] ?: return "$path.$k: missing here, Apple TV has ${want[k]}"
                val w = want[k] ?: return "$path.$k: extra here, $g"
                firstDifference(g, w, "$path.$k")?.let { return it }
            }
            return null
        }
        if (got is JsonArray && want is JsonArray) {
            for (i in 0 until maxOf(got.size, want.size)) {
                if (i >= got.size || i >= want.size) return "$path: ${got.size} entries here, Apple TV has ${want.size}"
                firstDifference(got[i], want[i], "$path[$i]")?.let { return it }
            }
            return null
        }
        return if (got == want) null else "$path: here $got, Apple TV $want"
    }

    @Test
    fun everyCaseMatchesTheAppleTvByteForByte() {
        assertTrue("golden file has cases", cases.isNotEmpty())
        val failures = cases.mapNotNull { c ->
            val name = c["name"]!!.jsonPrimitive.content
            firstDifference(dump(c["fixture"]!!.jsonObject), c["expect"]!!)?.let { "$name: $it" }
        }
        assertEquals("cases that differ from the Apple TV", emptyList<String>(), failures)
    }

    @Test
    fun theGoldenFileCoversWhatItClaims() {
        val backends = cases.flatMap { c -> c["fixture"]!!.jsonObject["items"]!!.jsonArray.mapNotNull { (it.jsonObject["backend"] as? JsonPrimitive)?.content } }.toSet()
        assertTrue("Plex, Jellyfin and Emby: $backends", backends.containsAll(listOf("plex", "jellyfin", "emby")))
        val dayLengths = HashSet<Long>()
        for (c in cases) {
            val fx = c["fixture"]!!.jsonObject
            val m = DailyManifest(ZoneId.of(fx["zone"]!!.jsonPrimitive.content), InMemoryManifestStore())
            for (t in fx["days"]!!.jsonArray) {
                val ms = t.jsonPrimitive.long * 1000
                dayLengths.add((m.startOfNextLocalDayMs(ms) - m.startOfLocalDayMs(ms)) / 3_600_000)
            }
        }
        assertTrue("a 23-hour and a 25-hour day: $dayLengths", 23L in dayLengths && 25L in dayLengths)
    }

    /** Negative control: the comparison catches a pool in the wrong order. */
    @Test
    fun aShuffledPoolFailsTheGoldenFile() {
        val c = cases.first()
        val fx = c["fixture"]!!.jsonObject
        val channels = JsonArray(fx["channels"]!!.jsonArray.map { row ->
            val o = row.jsonObject
            JsonObject(o + ("pool" to JsonArray(o["pool"]!!.jsonArray.reversed())))
        })
        val shuffled = JsonObject(fx + ("channels" to channels))
        assertTrue(firstDifference(dump(shuffled), c["expect"]!!) != null)
    }
}
