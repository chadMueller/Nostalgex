package com.muellhaus.nostalgex.engine

import kotlinx.serialization.Serializable
import kotlinx.serialization.json.Json
import java.time.Instant
import java.time.LocalDate
import java.time.ZoneId
import kotlin.math.abs
import kotlin.math.floor
import kotlin.math.max
import kotlin.math.min

/**
 * Daily 24h EPG manifests, a port of scripts/nostalgex-daily-manifest.js, which mirrors the
 * Apple TV's SchedulePoolOrdering.swift, DailyManifestScheduler.swift, DailyManifestStore.swift,
 * ChannelSchedule.swift and AppState.advanceToNextItem. The Apple TV is the reference;
 * scripts/schedule-parity-golden.json, generated by its own code, holds this file to the same
 * answers (ScheduleParityGoldenTest).
 *
 * The running order depends on the pool's order, so a pool must be in library order as the
 * server lists it, never shuffled, with minutes truncated (minutesFromPlexMs, minutesFromTicks).
 *
 * A day is packed for the whole lineup at once ([setLineup], packLineupDay): channels in
 * priority order, each in its own running order except that a programme another channel
 * already has on in the same slot waits for a later one (pickCandidate, [LOOKAHEAD]). What is
 * stored stays put. So which channels are in the guide is an input too: two devices with the
 * same library, lineup and history air the same day.
 *
 * Where the JS reads the browser's local time zone, this takes [zone]. Every public call is
 * synchronized: the lineup's day is packed once, whichever thread asks first.
 */
class DailyManifest(private val zone: ZoneId, private val store: ManifestStore) {

    // ── Local days ───────────────────────────────────────────────────────

    fun localDate(ms: Long): LocalDate = Instant.ofEpochMilli(ms).atZone(zone).toLocalDate()

    fun localDayKey(ms: Long): String = localDate(ms).toString()

    /** Where midnight is skipped (Santiago) this is the first moment of the day, as in JS. */
    fun startOfLocalDayMs(ms: Long): Long = localDate(ms).atStartOfDay(zone).toInstant().toEpochMilli()

    /** 36 hours after a day's start is always inside the next day. */
    fun startOfNextLocalDayMs(ms: Long): Long = startOfLocalDayMs(startOfLocalDayMs(ms) + 36 * 3_600_000L)

    /** 12 hours before a day's start is always inside the day before. */
    fun previousLocalDayKey(ms: Long): String = localDayKey(startOfLocalDayMs(ms) - 12 * 3_600_000L)

    private fun localDayLengthSec(sec: Long): Long {
        val start = startOfLocalDayMs(sec * 1000)
        return (startOfNextLocalDayMs(start) - start) / 1000
    }

    fun localDayNumber(ms: Long): Long = Math.floorDiv(startOfLocalDayMs(ms), 86_400_000L)

    // ── The store ────────────────────────────────────────────────────────

    private fun storageKey(serverKey: String, channelId: Int, dayKey: String) =
        "$MANIFEST_PREFIX${serverKey}_${channelId}_$dayKey"

    private fun readManifest(key: String): Manifest? =
        store.get(key)?.let { runCatching { json.decodeFromString<Manifest>(it) }.getOrNull() }

    private fun loadManifest(serverKey: String, channelId: Int, dayKey: String, poolFP: String): Manifest? {
        val manifest = readManifest(storageKey(serverKey, channelId, dayKey)) ?: return null
        if (manifest.schemaVersion != SCHEMA_VERSION || manifest.poolFingerprint != poolFP) return null
        return manifest
    }

    private fun saveManifest(serverKey: String, manifest: Manifest) {
        store.set(storageKey(serverKey, manifest.channelId, manifest.dayKey), json.encodeToString(manifest))
    }

    /** The stored day's blocks, whatever version stored them (empty if none). */
    private fun storedBlocks(serverKey: String, channelId: Int, dayKey: String): List<StoredBlock> =
        readManifest(storageKey(serverKey, channelId, dayKey))?.blocks ?: emptyList()

    @Synchronized
    fun clearManifests(serverKey: String) {
        val prefix = "$MANIFEST_PREFIX${serverKey}_"
        store.keys().filter { it.startsWith(prefix) }.forEach(store::remove)
        occupancyMemo = null
        lineupGeneration++
    }

    /** Drops stored days before yesterday: the next day only ever reads the one before it. */
    fun pruneManifests(serverKey: String, nowMs: Long) {
        val prefix = "$MANIFEST_PREFIX${serverKey}_"
        val keep = previousLocalDayKey(nowMs)
        store.keys().filter { it.startsWith(prefix) && it.substringAfterLast('_') < keep }.forEach(store::remove)
    }

    // ── Across channels: one title on one channel at a time ──────────────
    // Mirrors DailyManifestScheduler's lineup packing and ScheduleOccupancy.

    /**
     * What the other channels have on, by title. [overlap] is the seconds of [s, e) that some
     * other channel already airs the title for. A time-gated channel asks with `skipGated`: it
     * gives way to the rest of the lineup, never to another time-gated one, so its day can't
     * depend on the hour that one was first built.
     */
    class Occupancy {
        private class Slot(val ch: Int, val s: Long, val e: Long, val gated: Boolean)
        private val byKey = HashMap<String, MutableList<Slot>>()

        fun add(channelId: Int, ratingKey: String, s: Long, e: Long, gated: Boolean) {
            if (e <= s) return
            byKey.getOrPut(ratingKey) { ArrayList() }.add(Slot(channelId, s, e, gated))
        }

        fun overlap(ratingKey: String, s: Long, e: Long, channelId: Int, skipGated: Boolean): Long {
            val list = byKey[ratingKey] ?: return 0
            var sec = 0L
            for (x in list) {
                if (x.ch == channelId || (skipGated && x.gated)) continue
                val lo = max(s, x.s)
                val hi = min(e, x.e)
                if (hi > lo) sec += hi - lo
            }
            return sec
        }
    }

    private class Entry(val channel: ScheduleChannel, val pool: List<MediaItem>)

    private class Memo(val key: String, val generation: Int, val occupancy: Occupancy)

    // The lineup's day as packLineupDay last saw it, for channels off the guide only.
    private var occupancyMemo: Memo? = null
    private var lineupGeneration = 0

    // The guide's channels with the pools they air from. Unset, a channel packs alone.
    private var lineupSource: (() -> List<Pair<ScheduleChannel, List<MediaItem>>>)? = null

    /** Registers the guide's lineup: its channels with the pools they air from now. Null packs each channel alone. */
    @Synchronized
    fun setLineup(source: (() -> List<Pair<ScheduleChannel, List<MediaItem>>>)?) {
        lineupSource = source
        occupancyMemo = null
    }

    private fun currentLineup(): MutableList<Entry> {
        val seen = HashSet<Int>()
        val out = ArrayList<Entry>()
        for ((channel, pool) in lineupSource?.invoke() ?: emptyList()) {
            if (!seen.add(channel.id)) continue
            val valid = pool.filter { it.duration > 0 }
            if (valid.isNotEmpty()) out.add(Entry(channel, valid))
        }
        return out
    }

    /**
     * Packs one local day for the lineup's channels whose day isn't stored yet, together, so no
     * title is on two of them at once. Days already stored, and the programmes that run over
     * from the day before, are fixed. `extra` is one more channel not in the guide, packed
     * after the lineup against it and seen by nothing. Returns channel id to its day's blocks.
     * Mirrors DailyManifestScheduler.packLineupDay.
     */
    private fun packLineupDay(entries: List<Entry>, extra: Entry?, atMs: Long, serverKey: String): Map<Int, List<StoredBlock>> {
        val dayStartSec = Math.floorDiv(startOfLocalDayMs(atMs), 1000L)
        val dayKey = localDayKey(atMs)
        val dayNumber = localDayNumber(atMs)
        val yesterdayKey = previousLocalDayKey(atMs)
        // The day, and which channels the guide holds, so the memo can't outlive the lineup it was made from.
        val memoKey = "$serverKey|$dayKey|${entries.map { it.channel.id }.sorted().joinToString(",")}"
        val memo = occupancyMemo
        if (extra != null && memo != null && memo.key == memoKey && memo.generation == lineupGeneration) {
            val prev = storedBlocks(serverKey, extra.channel.id, yesterdayKey)
            val packed = packDay(extra.pool, dayStartSec, dayNumber, extra.channel.id, prev.mapTo(HashSet()) { it.ratingKey },
                extra.channel.isPremiereChannel, prev.lastOrNull()?.ratingKey, memo.occupancy, extra.channel.gated)
            saveManifest(serverKey, Manifest(SCHEMA_VERSION, extra.channel.id, dayKey, poolFingerprint(extra.pool), packed))
            return mapOf(extra.channel.id to packed)
        }
        val occupancy = Occupancy()
        val packedBy = HashMap<Int, List<StoredBlock>>()
        val all = sortByLineupPriority(entries).toMutableList()
        if (extra != null) all.add(extra)
        val yesterday = HashMap<Int, List<StoredBlock>>()
        for (entry in all) {
            val id = entry.channel.id
            val prev = storedBlocks(serverKey, id, yesterdayKey)
            yesterday[id] = prev
            // What runs past midnight from yesterday is on air today too (the guide's channels' only).
            if (entry !== extra) for (b in prev) if (b.endSec > dayStartSec) occupancy.add(id, b.ratingKey, b.startSec, b.endSec, entry.channel.gated)
        }
        val toPack = ArrayList<Pair<Entry, String>>()
        for (entry in all) {
            val fp = poolFingerprint(entry.pool)
            val cached = loadManifest(serverKey, entry.channel.id, dayKey, fp)
            if (cached != null) {
                if (entry !== extra) for (b in cached.blocks) occupancy.add(entry.channel.id, b.ratingKey, b.startSec, b.endSec, entry.channel.gated)
                packedBy[entry.channel.id] = cached.blocks
            } else {
                toPack.add(entry to fp)
            }
        }
        for ((entry, fp) in toPack) {
            val channel = entry.channel
            val prev = yesterday.getValue(channel.id)
            val packed = packDay(entry.pool, dayStartSec, dayNumber, channel.id, prev.mapTo(HashSet()) { it.ratingKey },
                channel.isPremiereChannel, prev.lastOrNull()?.ratingKey, occupancy, channel.gated)
            saveManifest(serverKey, Manifest(SCHEMA_VERSION, channel.id, dayKey, fp, packed))
            packedBy[channel.id] = packed
            if (entry !== extra) {
                for (b in packed) occupancy.add(channel.id, b.ratingKey, b.startSec, b.endSec, channel.gated)
                lineupGeneration++
            }
        }
        // Everything the guide's channels air this day, for the next channel off the guide.
        occupancyMemo = Memo(memoKey, lineupGeneration, occupancy)
        return packedBy
    }

    /**
     * Which of the first [LOOKAHEAD] programmes in `queue` airs at `t`: the first one no other
     * channel has on during its slot; failing that, -1 when `mustFit`, else the one that
     * overlaps least (the earliest of those). `avoidKey` (what just played here) is passed over
     * while there is anything else, and a later part of a story never goes ahead of an earlier
     * one waiting before it. Mirrors DailyManifestScheduler.pickCandidate.
     */
    private fun pickCandidate(
        queue: List<MediaItem>, t: Long, playSec: (Int) -> Long, occupancy: Occupancy?, channelId: Int,
        avoidKey: String?, mustFit: Boolean, skipGated: Boolean,
    ): Int {
        val n = min(LOOKAHEAD, queue.size)
        var best = -1
        var bestOverlap = Long.MAX_VALUE
        for (i in 0 until n) {
            val item = queue[i]
            if (n > 1 && avoidKey != null && item.ratingKey == avoidKey) continue
            if (i > 0 && waitsForEarlierPart(queue, i)) continue
            val ov = occupancy?.overlap(item.ratingKey, t, t + playSec(i), channelId, skipGated) ?: 0L
            if (ov == 0L) return i
            if (ov < bestOverlap) {
                bestOverlap = ov
                best = i
            }
        }
        if (mustFit) return -1
        return if (best >= 0) best else 0
    }

    // ── Packing a day ────────────────────────────────────────────────────

    fun packDay(
        pool: List<MediaItem>,
        dayStartSec: Long,
        dayNumber: Long,
        channelId: Int,
        yesterdayAired: Set<String>,
        isPremiereChannel: Boolean,
        yesterdayLastRatingKey: String?,
        occupancy: Occupancy? = null,
        gated: Boolean = false,
    ): List<StoredBlock> {
        val dayEndSec = dayStartSec + localDayLengthSec(dayStartSec)
        val totalPoolSec = pool.sumOf { it.duration.toLong() * 60 }
        if (totalPoolSec <= 0) return emptyList()

        val unplayed = pool.filter { it.ratingKey !in yesterdayAired }
        val interleaved = interleaveByShow(unplayed, channelId.toLong(), dayNumber)
        val promoted = if (isPremiereChannel) promoteRecentlyAdded(interleaved, dayStartSec, channelId) else interleaved
        val unplayedOrdered = groupSequelParts(promoted).toMutableList()

        // Cross-day seam: never lead off with the title that finished just before midnight.
        if (yesterdayLastRatingKey != null && unplayedOrdered.size > 1 &&
            unplayedOrdered[0].ratingKey == yesterdayLastRatingKey
        ) {
            unplayedOrdered.add(unplayedOrdered.removeAt(0))
        }
        val blocks = ArrayList<StoredBlock>()
        var t = dayStartSec

        // In the channel's order, except that a programme another channel has on in the same
        // slot waits for a later one (pickCandidate). It stays in the queue, so it still airs
        // today if the day has room. When nothing waiting fits, the filler loop below goes on.
        val queue = unplayedOrdered.filter { it.duration > 0 }.toMutableList()
        while (queue.isNotEmpty() && t < dayEndSec) {
            val j = pickCandidate(queue, t, { queue[it].duration.toLong() * 60 }, occupancy, channelId, null, true, gated)
            if (j < 0) break
            val item = queue.removeAt(j)
            val dur = item.duration.toLong() * 60
            blocks.add(StoredBlock(item.ratingKey, t, t + dur))
            t += dur
        }

        if (t < dayEndSec) {
            // Filler loop: no premiere promotion, sequels only.
            val orderedFull = groupSequelParts(interleaveByShow(pool, channelId.toLong(), dayNumber + 1))
            val goldenShift = floor(totalPoolSec * 0.6180339887).toLong()
            val offsetSec = (dayNumber * goldenShift) % totalPoolSec

            var elapsed = 0L
            var cycleIndex = 0
            var offsetInItem = offsetSec
            for (i in orderedFull.indices) {
                val d = orderedFull[i].duration.toLong() * 60
                if (elapsed + d > offsetSec) {
                    cycleIndex = i
                    offsetInItem = offsetSec - elapsed
                    break
                }
                elapsed += d
            }

            // Wraparound seam: the cycle can land on the very item that just played.
            if (orderedFull.size > 1) {
                val lastPlayed = blocks.lastOrNull()?.ratingKey ?: yesterdayLastRatingKey
                if (lastPlayed != null && orderedFull[cycleIndex].ratingKey == lastPlayed) {
                    cycleIndex = (cycleIndex + 1) % orderedFull.size
                    offsetInItem = 0
                }
            }

            // The loop as a queue from the cycle's start: what airs goes to the back, so with
            // nothing on elsewhere this is the cycle in order. The first programme starts part
            // way in (offsetInItem) only if it airs first; one picked ahead of it starts at 0.
            val loop = (orderedFull.subList(cycleIndex, orderedFull.size) + orderedFull.subList(0, cycleIndex))
                .filter { it.duration > 0 }.toMutableList()
            var first = true
            while (t < dayEndSec && loop.isNotEmpty()) {
                val remainingDay = dayEndSec - t
                val isFirst = first
                val playFor = { i: Int -> min(loop[i].duration.toLong() * 60 - (if (isFirst && i == 0) offsetInItem else 0L), remainingDay) }
                val lastKey = blocks.lastOrNull()?.ratingKey ?: yesterdayLastRatingKey
                val j = pickCandidate(loop, t, playFor, occupancy, channelId, lastKey, false, gated)
                val playSec = playFor(j)
                val item = loop.removeAt(j)
                loop.add(item)
                first = false
                blocks.add(StoredBlock(item.ratingKey, t, t + playSec))
                t += playSec
            }
        }

        return blocks
    }

    private fun resolveBlocks(stored: List<StoredBlock>, pool: List<MediaItem>): List<Block> {
        val lookup = pool.associateBy { it.ratingKey }
        return stored.mapNotNull { b -> lookup[b.ratingKey]?.let { Block(it, b.startSec, b.endSec) } }
    }

    @Synchronized
    fun getManifestBlocks(channel: ScheduleChannel, pool: List<MediaItem>, atMs: Long, serverKey: String): List<Block> {
        val validPool = pool.filter { it.duration > 0 }
        if (validPool.isEmpty()) return emptyList()

        val dayStartSec = Math.floorDiv(startOfLocalDayMs(atMs), 1000L)
        val dayKey = localDayKey(atMs)
        val poolFP = poolFingerprint(validPool)
        val channelId = channel.id

        loadManifest(serverKey, channelId, dayKey, poolFP)?.let { return resolveBlocks(it.blocks, validPool) }

        // Not stored: pack the day for the whole lineup at once. This channel takes its place
        // in the lineup with the pool it was asked with; one the guide doesn't carry packs after
        // the lineup, against it, so it never changes what the guide's channels air.
        val lineup = currentLineup()
        val at = lineup.indexOfFirst { it.channel.id == channelId }
        val self = Entry(channel, validPool)
        if (at >= 0) lineup[at] = self
        val packed = packLineupDay(lineup, if (at >= 0) null else self, atMs, serverKey)[channelId]
        return resolveBlocks(packed ?: emptyList(), validPool)
    }

    // ── What airs: the guide, conflicts, the next pick ───────────────────

    /** Every block of each local day from `fromSec`'s to `toSec`'s that overlaps [fromSec, toSec). */
    fun blocksInRange(channel: ScheduleChannel, pool: List<MediaItem>, fromSec: Long, toSec: Long, serverKey: String): List<Block> {
        val result = ArrayList<Block>()
        var cursor = startOfLocalDayMs(fromSec * 1000)
        val endDay = startOfLocalDayMs(toSec * 1000)
        while (cursor <= endDay) {
            for (b in getManifestBlocks(channel, pool, cursor + 3_600_000L, serverKey)) {
                if (b.endSec > fromSec && b.startSec < toSec) result.add(b)
            }
            // The same clock time a day on, as calendar.date(byAdding: .day) and JS setDate.
            cursor = Instant.ofEpochMilli(cursor).atZone(zone).plusDays(1).toInstant().toEpochMilli()
        }
        return result.sortedBy { it.startSec }
    }

    /**
     * The guide's view of a channel at `nowSec`: a 24-hour window from the current half hour,
     * what is on now, what is next and how far in. Null when the channel has nothing.
     */
    fun buildSchedule(channel: ScheduleChannel, pool: List<MediaItem>, nowSec: Double, serverKey: String): Schedule? {
        val nowUnix = floor(nowSec).toLong()
        val windowStart = Math.floorDiv(nowUnix, 1800L) * 1800
        val windowEnd = windowStart + 86_400
        val dayBlocks = blocksInRange(channel, pool, windowStart, windowEnd, serverKey)
        if (dayBlocks.isEmpty()) return null
        val entries = ArrayList<ScheduleEntry>()
        var nowPlaying: ScheduleEntry? = null
        for (b in dayBlocks) {
            if (!(b.endSec > windowStart && b.startSec < windowEnd)) continue
            val isNow = b.startSec <= nowSec && b.endSec > nowSec
            val entry = ScheduleEntry("${b.item.ratingKey}_${b.startSec}", b.item, b.startSec, b.endSec, isNow, false)
            entries.add(entry)
            if (isNow) nowPlaying = entry
        }
        val nowIdx = entries.indexOfFirst { it.isNowPlaying }
        val upNext = if (nowIdx >= 0 && nowIdx + 1 < entries.size) entries[nowIdx + 1] else null
        var progress = 0.0
        var elapsedSeconds = 0L
        nowPlaying?.let {
            val elapsed = nowSec - it.startSec
            val dur = it.endSec - it.startSec
            progress = if (dur > 0) elapsed / dur else 0.0
            elapsedSeconds = max(0L, elapsed.toLong())
        }
        return Schedule(entries, nowPlaying, upNext, progress, elapsedSeconds)
    }

    /** One title on two channels at once: the lowest channel id keeps it. Changes `schedules` in place. */
    fun resolveConflicts(schedules: MutableMap<Int, Schedule>): MutableMap<Int, Schedule> {
        val byItem = LinkedHashMap<String, MutableList<Int>>()
        for ((channelId, schedule) in schedules) {
            val key = schedule.nowPlaying?.item?.ratingKey ?: continue
            byItem.getOrPut(key) { ArrayList() }.add(channelId)
        }
        for (ids in byItem.values) {
            if (ids.size < 2) continue
            for (id in ids.sorted().drop(1)) {
                val old = schedules.getValue(id)
                val entries = old.entries.toMutableList()
                val i = entries.indexOfFirst { it.isNowPlaying }
                if (i >= 0) entries[i] = entries[i].copy(isNowPlaying = false, isConflict = true)
                val oldNext = old.upNext
                if (oldNext != null) {
                    val nowPlaying = oldNext.copy(isNowPlaying = true, isConflict = false)
                    val j = entries.indexOfFirst { it.id == oldNext.id }
                    val upNext = if (j >= 0 && j + 1 < entries.size) entries[j + 1] else null
                    schedules[id] = Schedule(entries, nowPlaying, upNext, 0.0, 0)
                } else {
                    schedules[id] = old.copy(entries = entries)
                }
            }
        }
        return schedules
    }

    /** What tuning to a channel plays, and from where. Null where the Apple TV would pick at random. */
    fun tuneIn(channel: ScheduleChannel, pool: List<MediaItem>, precomputed: Schedule?, nowSec: Double, serverKey: String): Pick? {
        val usable = precomputed?.takeIf { scheduleIsCurrent(it, nowSec) }
        val schedule = usable ?: buildSchedule(channel, pool, nowSec, serverKey) ?: return null
        val np = schedule.nowPlaying ?: return null
        return Pick(np.item, liveElapsedSeconds(schedule, nowSec) ?: schedule.elapsedSeconds)
    }

    /** The first other channel whose programme now is `item`, or null. */
    fun findConflict(item: MediaItem, excludingChannelId: Int, channels: List<Pair<ScheduleChannel, List<MediaItem>>>, nowSec: Double, serverKey: String): Int? {
        for ((channel, pool) in channels) {
            if (channel.id == excludingChannelId) continue
            val schedule = buildSchedule(channel, pool, nowSec, serverKey)
            if (schedule?.nowPlaying?.item?.ratingKey == item.ratingKey) return channel.id
        }
        return null
    }

    /**
     * What a channel plays next when its programme ends: the schedule's programme if it has
     * moved on, otherwise the next one; never the title another channel has on right now.
     */
    fun advancePick(
        channel: ScheduleChannel,
        pool: List<MediaItem>,
        prevRatingKey: String?,
        nowSec: Double,
        channels: List<Pair<ScheduleChannel, List<MediaItem>>>,
        serverKey: String,
        fromNaturalEnd: Boolean = true,
    ): Pick? {
        val schedule = buildSchedule(channel, pool, nowSec, serverKey) ?: return null
        val moved = schedule.nowPlaying?.item?.ratingKey != prevRatingKey
        var pick = if (moved) schedule.nowPlaying?.item else (schedule.upNext?.item ?: schedule.nowPlaying?.item)
        var seekSeconds = if (moved && pick != null && !fromNaturalEnd) schedule.elapsedSeconds else 0L
        if (pick != null && findConflict(pick, channel.id, channels, nowSec, serverKey) != null) {
            val key = pick.ratingKey
            val idx = schedule.entries.indexOfFirst { it.item.ratingKey == key }
            if (idx >= 0 && idx + 1 < schedule.entries.size) {
                pick = schedule.entries[idx + 1].item
                seekSeconds = 0
            }
        }
        return pick?.let { Pick(it, seekSeconds) }
    }

    companion object {
        private const val MANIFEST_PREFIX = "plex90_manifest_"
        /**
         * 2: the schedule follows the Apple TV's. 3: the lineup's days are packed together, so
         * one title is never on two channels at once; a day stored before is packed again once.
         */
        private const val SCHEMA_VERSION = 3

        /** How far down its running order a channel looks for a programme no other channel has on. DailyManifestScheduler.lookahead. */
        const val LOOKAHEAD = 8

        /**
         * The order channels claim programmes in: time-gated channels last, so the others' days
         * never depend on when a device first built them; then by channel id. Stable.
         */
        private fun sortByLineupPriority(entries: List<Entry>) =
            entries.sortedWith(compareBy<Entry>({ if (it.channel.gated) 1 else 0 }, { it.channel.id }))

        private data class PartMark(val base: String, val ordinal: Int)

        /** The story and part of a multi-part film ("... Part 2"), or null. Same test as groupSequelParts. */
        private fun sequelMark(item: MediaItem): PartMark? {
            if (item.type != "movie") return null
            val match = SEQUEL_MARKER.matchEntire(item.title) ?: return null
            val base = JsText.trim(match.groupValues[1].lowercase())
            return if (base.isEmpty()) null else PartMark(base, match.groupValues[2].toInt())
        }

        /** A later part may not jump ahead of an earlier part of the same story still waiting before it. */
        private fun waitsForEarlierPart(queue: List<MediaItem>, i: Int): Boolean {
            val mark = sequelMark(queue[i]) ?: return false
            for (k in 0 until i) {
                val other = sequelMark(queue[k]) ?: continue
                if (other.base == mark.base && other.ordinal < mark.ordinal) return true
            }
            return false
        }
        private val json = Json { ignoreUnknownKeys = true }

        /** A week of recency earns priority placement, from 7 PM, in 15-minute slots to midnight. */
        private const val PREMIERE_WINDOW_SECONDS = 7L * 86_400
        private const val PREMIERE_ANCHOR_SECONDS = 19L * 3600
        private const val PREMIERE_SPREAD_SECONDS = 5L * 3600
        private const val PREMIERE_SLOT_SECONDS = 15L * 60

        fun minutesFromPlexMs(ms: Long?): Int = if (ms != null && ms > 0) (ms / 60_000).toInt() else 0

        fun minutesFromTicks(ticks: Long?): Int = if (ticks != null && ticks > 0) (ticks / 600_000_000).toInt() else 0

        /** 0 when it doesn't parse: an unreadable date reads as "not recent", never "added now". */
        fun unixSecondsFromISO(iso: String?): Long {
            if (iso.isNullOrEmpty()) return 0
            return runCatching { Math.floorDiv(Instant.parse(iso).toEpochMilli(), 1000L) }.getOrDefault(0)
        }

        fun scheduleIsCurrent(schedule: Schedule?, nowSec: Double): Boolean {
            val np = schedule?.nowPlaying ?: return false
            return np.startSec <= nowSec && nowSec < np.endSec
        }

        /** Seconds into what is on now, from the clock, capped at the programme's length. */
        fun liveElapsedSeconds(schedule: Schedule?, nowSec: Double): Long? {
            val np = schedule?.nowPlaying ?: return null
            val total = max(1L, np.item.duration.toLong() * 60)
            return max(0L, min(total, (nowSec - np.startSec).toLong()))
        }

        // ── Seeded shuffle: splitmix64-seeded xorshift64, Swift's shuffle ────

        private fun splitmix64(x: ULong): ULong {
            var z = x + 0x9E3779B97F4A7C15uL
            z = (z xor (z shr 30)) * 0xBF58476D1CE4E5B9uL
            z = (z xor (z shr 27)) * 0x94D049BB133111EBuL
            return z xor (z shr 31)
        }

        private class SeededRng(seed: ULong) {
            private var state = splitmix64(seed).let { if (it == 0uL) 1uL else it }

            fun next(): ULong {
                state = state xor (state shl 13)
                state = state xor (state shr 7)
                state = state xor (state shl 17)
                return state
            }

            /** The Swift stdlib's `next(upperBound:)`, Lemire's nearly-divisionless draw. */
            fun boundedNext(upperBound: Int): Int {
                val u = upperBound.toULong()
                var r = next()
                var low = r * u
                if (low < u) {
                    val t = (0uL - u) % u
                    while (low < t) {
                        r = next()
                        low = r * u
                    }
                }
                return mulHigh(r, u).toInt()
            }

            /** The high 64 bits of a * u, for u below 2^32. */
            private fun mulHigh(a: ULong, u: ULong): ULong {
                val hi = a shr 32
                val lo = a and 0xFFFFFFFFuL
                return (hi * u + ((lo * u) shr 32)) shr 32
            }
        }

        private fun <T> swiftShuffle(list: MutableList<T>, rng: SeededRng) {
            var amount = list.size
            var currentIndex = 0
            while (amount > 1) {
                val random = rng.boundedNext(amount)
                amount -= 1
                val j = currentIndex + random
                val tmp = list[currentIndex]
                list[currentIndex] = list[j]
                list[j] = tmp
                currentIndex += 1
            }
        }

        fun interleaveByShow(items: List<MediaItem>, seed: Long, dayNumber: Long): List<MediaItem> {
            if (items.size <= 1) return items.toList()

            val groups = LinkedHashMap<String, MutableList<MediaItem>>()
            for (item in items) {
                // An episode's `title` is its show's name.
                val key = if (item.type == "episode") item.title else "movie_${item.ratingKey}"
                groups.getOrPut(key) { ArrayList() }.add(item)
            }

            val rng = SeededRng((abs(seed) + 1).toULong() + dayNumber.toULong())
            for (list in groups.values) swiftShuffle(list, rng)
            val orderedGroups = groups.values.toMutableList()
            swiftShuffle(orderedGroups, rng)

            val maxConsecutive = 2
            val result = ArrayList<MediaItem>(items.size)
            val positions = IntArray(orderedGroups.size)
            var groupIndex = 0
            var exhausted = 0

            while (exhausted < orderedGroups.size) {
                var attempts = 0
                while (positions[groupIndex] >= orderedGroups[groupIndex].size) {
                    groupIndex = (groupIndex + 1) % orderedGroups.size
                    attempts++
                    if (attempts > orderedGroups.size) break
                }
                if (attempts > orderedGroups.size) break

                val group = orderedGroups[groupIndex]
                val pos = positions[groupIndex]
                val take = min(maxConsecutive, group.size - pos)
                for (i in 0 until take) result.add(group[pos + i])
                positions[groupIndex] = pos + take
                if (positions[groupIndex] >= group.size) exhausted++
                groupIndex = (groupIndex + 1) % orderedGroups.size
            }
            return result
        }

        /** FNV-1a over the ratingKey, murmur3 finalizer: a premiere slot per (channel, item). */
        fun premiereOffset(channelId: Int, ratingKey: String): Long {
            val slots = max(1L, PREMIERE_SPREAD_SECONDS / PREMIERE_SLOT_SECONDS).toULong()
            var x = channelId.toLong().toULong() + 0x9E3779B97F4A7C15uL
            for (byte in ratingKey.encodeToByteArray()) {
                x = (x xor byte.toUByte().toULong()) * 0x00000100000001B3uL
            }
            x = x xor (x shr 33)
            x *= 0xFF51AFD7ED558CCDuL
            x = x xor (x shr 33)
            return PREMIERE_ANCHOR_SECONDS + (x % slots).toLong() * PREMIERE_SLOT_SECONDS
        }

        fun promoteRecentlyAdded(items: List<MediaItem>, dayStartUnix: Long, channelId: Int, windowSeconds: Long = PREMIERE_WINDOW_SECONDS): List<MediaItem> {
            if (items.size <= 1) return items
            val cutoff = dayStartUnix - windowSeconds
            val isRecent = { i: MediaItem -> i.addedAt > 0 && i.addedAt >= cutoff }
            val recent = items.filter(isRecent)
            if (recent.isEmpty() || recent.size >= items.size) return items
            val rest = items.filterNot(isRecent)

            // Earlier premieres first, so two an hour apart stay an hour apart. ratingKey breaks ties.
            val targets = recent.map { it to premiereOffset(channelId, it.ratingKey) }
                .sortedWith(compareBy<Pair<MediaItem, Long>> { it.second }.thenBy { it.first.ratingKey })

            val out = rest.toMutableList()
            for ((item, offset) in targets) {
                var insertAt = out.size
                var cumulativeSeconds = 0L
                for (index in out.indices) {
                    if (cumulativeSeconds >= offset) {
                        insertAt = index
                        break
                    }
                    cumulativeSeconds += out[index].duration.toLong() * 60
                }
                out.add(insertAt, item)
            }
            return out
        }

        /** Anchored to the END of the title so mid-title words never match. */
        private val SEQUEL_MARKER = Regex(
            "^(${JsText.DOT}*?)[${JsText.WS}:,-]+(?:part|pt\\.?)[${JsText.WS}]*([0-9]{1,2})[${JsText.WS}]*$",
            RegexOption.IGNORE_CASE,
        )

        private data class SequelMark(val index: Int, val base: String, val ordinal: Int)

        fun groupSequelParts(items: List<MediaItem>): List<MediaItem> {
            if (items.size <= 1) return items

            val marked = ArrayList<SequelMark>()
            for ((index, it) in items.withIndex()) {
                if (it.type != "movie") continue
                val match = SEQUEL_MARKER.matchEntire(it.title) ?: continue
                val ordinal = match.groupValues[2].toInt()
                val base = JsText.trim(match.groupValues[1].lowercase())
                if (base.isEmpty()) continue
                marked.add(SequelMark(index, base, ordinal))
            }

            val groups = LinkedHashMap<String, MutableList<SequelMark>>()
            for (mark in marked) groups.getOrPut(mark.base) { ArrayList() }.add(mark)
            // Only real multi-part stories move; a lone "Part 2" stays put.
            val families = groups.values.filter { it.size > 1 }
            if (families.isEmpty()) return items

            val pulled = HashSet<Int>()
            val insertions = HashMap<Int, List<MediaItem>>()
            for (family in families) {
                val anchor = family.minOf { it.index }
                insertions[anchor] = family.sortedBy { it.ordinal }.map { items[it.index] }
                family.forEach { pulled.add(it.index) }
            }

            val result = ArrayList<MediaItem>(items.size)
            for (index in items.indices) {
                val inserted = insertions[index]
                if (inserted != null) result.addAll(inserted) else if (index !in pulled) result.add(items[index])
            }
            return result
        }

        /** Only decides whether a stored manifest is still valid; never feeds the order. */
        fun poolFingerprint(pool: List<MediaItem>): String {
            val keys = pool.map { it.ratingKey }.sorted().joinToString(",")
            var h = 0
            for (c in keys) h = (h shl 5) - h + c.code
            return h.toString()
        }
    }
}

/** Where manifests are kept: in memory for tests, SharedPreferences on the TV. */
interface ManifestStore {
    fun get(key: String): String?
    fun set(key: String, value: String)
    fun remove(key: String)
    fun keys(): Set<String>
}

class InMemoryManifestStore : ManifestStore {
    private val map = LinkedHashMap<String, String>()
    override fun get(key: String) = map[key]
    override fun set(key: String, value: String) { map[key] = value }
    override fun remove(key: String) { map.remove(key) }
    override fun keys(): Set<String> = map.keys.toSet()
    fun clear() = map.clear()
}

